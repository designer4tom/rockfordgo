<script>
    function footerSetTheme(theme) {
        if (theme === 'dark') {
            document.documentElement.classList.add('dark');
            localStorage.setItem('rr-theme', 'dark');
            document.getElementById('footerBtnDark').classList.add('font-semibold', 'text-gray-900');
            document.getElementById('footerBtnLight').classList.remove('font-semibold', 'text-gray-900');
        } else {
            document.documentElement.classList.remove('dark');
            localStorage.setItem('rr-theme', 'light');
            document.getElementById('footerBtnLight').classList.add('font-semibold', 'text-gray-900');
            document.getElementById('footerBtnDark').classList.remove('font-semibold', 'text-gray-900');
        }
    }
    // Set active button based on saved theme
    (function() {
        const t = localStorage.getItem('rr-theme') || 'light';
        const btn = document.getElementById(t === 'dark' ? 'footerBtnDark' : 'footerBtnLight');
        if (btn) btn.classList.add('font-semibold', 'text-gray-900');
    })();
</script>
